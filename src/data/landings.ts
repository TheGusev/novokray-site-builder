/** Прайс-строки конкретной посадочной: берём реальные цены из общего прайса. */
export function landingPrices(l: Landing): Array<{ label: string; price: string }> {
  const pest = PESTS[l.pest];
  const obj = OBJECTS[l.object];
  return obj.priceRows
    .map((row) => {
      const value = getLeadPrice(pest.priceKey, row);
      return value ? { label: row, price: `от ${formatRub(value)}` } : null;
    })
    .filter((x): x is { label: string; price: string } => x !== null);
}

/** Минимальная цена посадочной (для Offer / og:title). */
export function landingPriceFrom(l: Landing): number {
  const rows = landingPrices(l);
  const nums = rows.map((r) => Number(r.price.replace(/\D/g, "")));
  return nums.length ? Math.min(...nums) : 1500;
}

/** Посадочные, относящиеся к услуге (для блока перелинковки на /services/:slug). */
export function landingsForService(serviceSlug: string): Landing[] {
  return LANDINGS.filter((l) => PESTS[l.pest]?.serviceSlug === serviceSlug);
}
